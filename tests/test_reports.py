def test_excel_export_neutralises_formulas(data, client_for):
    student = db.session.get(Student, data.student_id)
    student.name = '=HYPERLINK("http://evil","x")'
    db.session.commit()
    add_session(data, present=[data.student_id])

    response = client_for(data.teacher).get(f'/export/{data.mca_id}/{data.sem1_id}/excel')
    sheet = openpyxl.load_workbook(io.BytesIO(response.data)).active
    names = [row[1] for row in sheet.iter_rows(min_row=2, values_only=True)]
    assert "'=HYPERLINK(\"http://evil\",\"x\")" in names
    assert sheet.cell(row=1, column=4).value == 'DBMS - MCA101'


