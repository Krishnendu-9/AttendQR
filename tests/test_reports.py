def test_semesters_sort_naturally(data, client_for):
    db.session.add(Semester(name='Semester 10', department_id=data.mca_id))
    db.session.commit()
    names = [s['name'] for s in client_for(data.principal).get(f'/api/semesters/{data.mca_id}').get_json()]
    assert names == ['Semester 1', 'Semester 2', 'Semester 10']
    assert sorted(['Sem 10', 'Sem 2', 'Sem 1'], key=natural_key) == ['Sem 1', 'Sem 2', 'Sem 10']


def test_principal_import_template_round_trips(data, client_for):
    client = client_for(data.principal)
    template = client.get('/students/import-template').get_data(as_text=True)
    headers, sample = list(csv.reader(io.StringIO(template)))
    row = dict(zip(headers, sample, strict=True))
    row.update(name='Template Student', roll_no='MCA777', email='template@example.com')

    out = io.StringIO()
    writer = csv.DictWriter(out, fieldnames=headers)
    writer.writeheader()
    writer.writerow(row)
    response = post(client, '/students/import', {
        'student_file': (io.BytesIO(out.getvalue().encode()), 'students.csv'),
    }, content_type='multipart/form-data', follow_redirects=True)
    assert 'Imported 1 student profile' in response.get_data(as_text=True), response.get_data(as_text=True)


