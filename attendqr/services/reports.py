# Matrix mark for a session held after the student moved to another class.
NOT_IN_CLASS = 'not_in_class'
# How that session shows in exports: an en dash, since a plain "-" would be escaped for Excel.
NOT_IN_CLASS_MARK = chr(0x2013)


def countable_session_clause():
    """Sessions that count as classes held.

    A session that was deactivated before anyone marked attendance is treated as
    void (typically generated by mistake), so it does not lower anyone's percentage.
    """
    has_attendance = exists().where(Attendance.session_id == ClassSession.id)
    return or_(ClassSession.is_active.is_(True), has_attendance)


def is_void_session(class_session, attendance_count):
    return not class_session.is_active and not attendance_count


def session_ids_select(session_query):
    return session_query.with_entities(ClassSession.id).order_by(None).statement


def attendance_counts(session_ids):
    """{session_id: number of students marked present} for the given sessions."""
    if not session_ids:
        return {}
    rows = (
        db.session.query(Attendance.session_id, func.count(Attendance.id))
        .filter(Attendance.session_id.in_(session_ids))
        .group_by(Attendance.session_id)
    )
    return dict(rows)


def total_attendance(session_query):
    return (
        db.session.query(func.count(Attendance.id))
        .filter(Attendance.session_id.in_(session_ids_select(session_query)))
        .scalar()
        or 0
    )


def classes_needed_for_target(attended, total, target):
    """Consecutive classes to attend so that attended/total reaches target percent.

    Solves (attended + n) / (total + n) >= target / 100 in integers; float maths
    rounds 0.8 * 6 up to 4.800000000000001 and over-counts by one.
    """
    if total == 0 or attended * 100 >= target * total:
        return 0
    if target >= 100:
        return 0
    return -(-(target * total - 100 * attended) // (100 - target))  # integer ceiling division


def build_student_attendance_summary(student):
    target = current_app.config['ATTENDANCE_TARGET']
    subjects = Subject.query.filter(
        Subject.department_id == student.department_id,
        Subject.semester_id == student.semester_id,
        Subject.name != SPECIAL_CLASS_SUBJECT_NAME,
    ).order_by(Subject.paper_code, Subject.name).all()
    subject_ids = [subject.id for subject in subjects]

    sessions = db.session.query(ClassSession.id, ClassSession.subject_id, ClassSession.created_at).filter(
        ClassSession.subject_id.in_(subject_ids), countable_session_clause(),
    ).all() if subject_ids else []
    attended_ids = {
        session_id for (session_id,) in db.session.query(Attendance.session_id)
        .join(ClassSession, ClassSession.id == Attendance.session_id)
        .filter(Attendance.student_id == student.id, ClassSession.subject_id.in_(subject_ids))
    } if subject_ids else set()

    leave = LeaveWindows([student.id])
    totals, attended_counts = {}, {}
    excused = 0
    for session_id, subject_id, created_at in sessions:
        if leave.excused(student.id, created_at):
            excused += 1  # on approved leave: counts neither way
            continue
        totals[subject_id] = totals.get(subject_id, 0) + 1
        if session_id in attended_ids:
            attended_counts[subject_id] = attended_counts.get(subject_id, 0) + 1

    rows = []
    overall_attended = overall_total = 0
    for subject in subjects:
        total = totals.get(subject.id, 0)
        attended = attended_counts.get(subject.id, 0)
        percentage = round(attended / total * 100, 2) if total else 0
        rows.append({
            'subject': subject,
            'attended': attended,
            'total': total,
            'percentage': percentage,
            'needed': classes_needed_for_target(attended, total, target),
            'safe': percentage >= target if total else True,
        })
        overall_attended += attended
        overall_total += total

    overall_percentage = round(overall_attended / overall_total * 100, 2) if overall_total else 0
    recent = (
        Attendance.query.options(joinedload(Attendance.session).joinedload(ClassSession.subject))
        .filter_by(student_id=student.id)
        .order_by(Attendance.timestamp.desc())
        .limit(8)
        .all()
    )

    return {
        'rows': rows,
        'recent': recent,
        'target': target,
        'overall_attended': overall_attended,
        'overall_total': overall_total,
        'overall_percentage': overall_percentage,
        'overall_needed': classes_needed_for_target(overall_attended, overall_total, target),
        'overall_safe': overall_percentage >= target if overall_total else True,
        'excused': excused,
    }


# ── Report filters ───────────────────────────────────────────

@dataclass
class ReportFilters:
    department_id: int | None
    semester_id: int | None
    subject_id: int | None
    parsed_from: date | None
    parsed_to: date | None
    date_from: str
    date_to: str
    error: str | None

    def query_args(self):
        """Optional filters to forward to the detailed view and exports."""
        args = {}
        if self.subject_id:
            args['subject_id'] = self.subject_id
        if self.date_from:
            args['date_from'] = self.date_from
        if self.date_to:
            args['date_to'] = self.date_to
        return args


def parse_report_filters(args, department_id=None, semester_id=None):
    parsed_from, parsed_to, date_from, date_to, error = parse_date_range(
        args.get('date_from'), args.get('date_to'), local_now().date()
    )
    return ReportFilters(
        department_id=department_id if department_id is not None else args.get('department_id', type=int),
        semester_id=semester_id if semester_id is not None else args.get('semester_id', type=int),
        subject_id=args.get('subject_id', type=int),
        parsed_from=parsed_from,
        parsed_to=parsed_to,
        date_from=date_from,
        date_to=date_to,
        error=error,
    )


def report_sessions_query(filters, countable_only=False):
    query = ClassSession.query.join(Subject).filter(
        Subject.department_id == filters.department_id,
        Subject.semester_id == filters.semester_id,
    )
    if user_role() == 'teacher':
        query = query.filter(own_teacher_filter(ClassSession.teacher_id))
    if filters.subject_id:
        query = query.filter(Subject.id == filters.subject_id)
    if filters.parsed_from:
        # The dates are the college's calendar days; stored times are UTC.
        query = query.filter(ClassSession.created_at >= local_day_start_utc(filters.parsed_from))
    if filters.parsed_to:
        query = query.filter(ClassSession.created_at < local_day_start_utc(filters.parsed_to + timedelta(days=1)))
    if countable_only:
        query = query.filter(countable_session_clause())
    return query


def is_special_session(class_session):
    return bool(class_session.subject and class_session.subject.name == SPECIAL_CLASS_SUBJECT_NAME)


def build_attendance_matrix(filters):
    """Students of the class with present/absent per countable session.

    Special classes are shown but, as on the student dashboard and the shortage
    list, not counted in each student's total and percentage.
    """
    session_query = report_sessions_query(filters, countable_only=True)
    sessions = (
        session_query.options(joinedload(ClassSession.subject))
        .order_by(ClassSession.created_at.desc())
        .all()
    )
    # (student_id, session_id) -> 'scan' or 'manual'; absent pairs are missing.
    attended = {
        (student_id, session_id): source
        for student_id, session_id, source in db.session.query(
            Attendance.student_id, Attendance.session_id, Attendance.source
        ).filter(Attendance.session_id.in_(session_ids_select(session_query)))
    } if sessions else {}

    members = class_roster(filters.department_id, filters.semester_id)
    leave = LeaveWindows(student.id for student, _ in members) if sessions else LeaveWindows(())
    rows = []
    for student, left_at in members:
        marks = {}
        for s in sessions:
            mark = attended.get((student.id, s.id))
            if not mark and not in_class_at(left_at, s.created_at):
                # Held after the student moved to another class: neither present nor absent.
                mark = NOT_IN_CLASS
            elif leave.excused(student.id, s.created_at):
                mark = ON_LEAVE  # approved leave: counts neither way
            marks[s.id] = mark
        counted_ids = [s.id for s in sessions
                       if not is_special_session(s) and marks[s.id] not in (NOT_IN_CLASS, ON_LEAVE)]
        if left_at is not None and all(mark == NOT_IN_CLASS for mark in marks.values()):
            continue  # Moved out before any of these sessions.
        present = sum(1 for session_id in counted_ids if marks[session_id])
        rows.append({
            'student': student,
            'left_at': left_at,
            'attendance': marks,
            'total': present,
            'counted': len(counted_ids),
            'percentage': round(present / len(counted_ids) * 100, 2) if counted_ids else 0,
        })
    return sessions, rows


