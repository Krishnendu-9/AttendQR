def session_header_lines(class_session):
    if class_session.special_title:
        return [class_session.special_title]
    subject = class_session.subject
    if not subject:
        return ['Special Class']
    paper_code = normalize_paper_code(subject.paper_code)
    return [subject.name, paper_code] if paper_code else [subject.name]


def _excel_safe(value):
    """Stop spreadsheet apps from treating user-entered text as a formula."""
    if isinstance(value, str) and value[:1] in ('=', '+', '-', '@', '\t', '\r'):
        return "'" + value
    return value


def export_filename(department, semester, sessions, filters):
    if filters.subject_id and sessions and sessions[0].subject:
        subject = sessions[0].subject
        base = normalize_paper_code(subject.paper_code) or subject.name
        name = f'{base}_attendance'
    else:
        base = department.branch_name or department.course_name
        name = f'{base}_{semester.name}_attendance'
    return ''.join(ch if ch.isalnum() or ch in '-_.' else '_' for ch in name)


MANUAL_MARK_LEGEND = "P = present (QR scan), P* = present (entered manually by staff), A = absent"
SPECIAL_CLASS_LEGEND = "Special classes are listed but not counted in Total and %."


MOVED_LEGEND = f"{NOT_IN_CLASS_MARK} = held after the student moved to another class (not counted)"


def attendance_mark(source):
    if source == NOT_IN_CLASS:
        return NOT_IN_CLASS_MARK
    if source == ON_LEAVE:
        return ON_LEAVE_MARK
    if not source:
        return 'A'
    return 'P*' if source == Attendance.SOURCE_MANUAL else 'P'


def export_name(row):
    """The student's name, marked when they have since moved to another class."""
    left_at = row.get('left_at')
    if left_at is None:
        return row['student'].name
    return f"{row['student'].name} (moved out {to_local(left_at):%d-%m-%Y})"


def build_export_rows(sessions, rows):
    headers = ['Roll No', 'Name', 'Email'] + [session_header_lines(s) for s in sessions] + ['Total', '%']
    data = []
    for row in rows:
        student = row['student']
        line = [student.roll_no, export_name(row), student.email]
        line += [attendance_mark(row['attendance'][s.id]) for s in sessions]
        line.append(row['total'])
        line.append(f"{round(row['total'] / row['counted'] * 100, 1)}%" if row['counted'] else "0%")
        data.append(line)
    return headers, data


def render_excel(headers, data, notes=(), title="Attendance Report"):
    workbook = openpyxl.Workbook()
    sheet = workbook.active or workbook.create_sheet()
    sheet.title = title
    header_font = openpyxl.styles.Font(color="FFFFFF", bold=True)
    header_fill = openpyxl.styles.PatternFill(start_color="366092", end_color="366092", fill_type="solid")

    for col_idx, header in enumerate(headers, 1):
        text = ' - '.join(header) if isinstance(header, list) else header
        cell = sheet.cell(row=1, column=col_idx, value=_excel_safe(text))
        cell.font = header_font
        cell.fill = header_fill
    for row_idx, row in enumerate(data, 2):
        for col_idx, value in enumerate(row, 1):
            sheet.cell(row=row_idx, column=col_idx, value=_excel_safe(value))
    for offset, note in enumerate(notes):
        cell = sheet.cell(row=len(data) + 3 + offset, column=1, value=_excel_safe(note))
        cell.font = openpyxl.styles.Font(italic=True, color="555555")

    buffer = io.BytesIO()
    workbook.save(buffer)
    buffer.seek(0)
    return buffer


def pdf_session_chunks(session_count, per_page):
    """Split session column indexes into groups that fit across one page."""
    if not session_count:
        return [range(0)]
    return [range(start, min(start + per_page, session_count)) for start in range(0, session_count, per_page)]


def render_pdf(headers, data, title, notes=()):
    """Attendance matrix as a landscape PDF.

    `headers` and each row are: Roll No, Name, Email, one column per session, Total, %.
    Sessions that do not fit across the page continue in further tables, each
    repeating the student and total columns, instead of being drawn off the page.
    """
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_CENTER, TA_LEFT
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import cm
    from reportlab.platypus import PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table

    buffer = io.BytesIO()
    margin = 1.5 * cm
    pagesize = landscape(A4)
    usable_width = pagesize[0] - 2 * margin
    doc = SimpleDocTemplate(buffer, pagesize=pagesize, leftMargin=margin, rightMargin=margin,
                            topMargin=margin, bottomMargin=margin)

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle('ReportTitle', parent=styles['Heading1'], fontSize=14,
                                 textColor=colors.HexColor('#366092'), spaceAfter=8, alignment=TA_LEFT)
    header_style = ParagraphStyle('HeaderCell', fontSize=7, textColor=colors.whitesmoke,
                                  alignment=TA_CENTER, leading=9)
    body_style = ParagraphStyle('BodyCell', fontSize=8, alignment=TA_CENTER, leading=10)

    def cell(value, style):
        # Paragraph parses markup, so every user-supplied value is escaped; only our own
        # line breaks between header parts are real markup.
        lines = value if isinstance(value, list) else [value]
        return Paragraph('<br/>'.join(escape('' if v is None else str(v)) for v in lines), style)

    # Fixed widths for Roll No, Name, Email, Total, %; sessions share the rest.
    lead_widths = [2.0 * cm, 3.2 * cm, 4.2 * cm]
    trail_widths = [1.1 * cm, 1.6 * cm]
    min_session_width, max_session_width = 1.5 * cm, 3.5 * cm
    session_space = usable_width - sum(lead_widths) - sum(trail_widths)
    num_sessions = max(len(headers) - 5, 0)
    chunks = pdf_session_chunks(num_sessions, max(1, int(session_space // min_session_width)))

    def chunk_columns(values, chunk):
        return list(values[:3]) + [values[3 + index] for index in chunk] + list(values[-2:])

    def build_table(chunk):
        table_data = [[cell(h, header_style) for h in chunk_columns(headers, chunk)]]
        table_data += [[cell(v, body_style) for v in chunk_columns(row, chunk)] for row in data]
        session_width = min(max(session_space / len(chunk), min_session_width), max_session_width) if chunk else 0
        col_widths = lead_widths + [session_width] * len(chunk) + trail_widths
        total_width = sum(col_widths)
        if total_width < usable_width:
            col_widths = [w * usable_width / total_width for w in col_widths]
        table = Table(table_data, colWidths=col_widths, repeatRows=1)
        table.setStyle(table_style)
        return table

    table_style = [
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#366092')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, 0), 7),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 8),
        ('TOPPADDING', (0, 0), (-1, 0), 8),
        ('BACKGROUND', (0, 1), (-1, -1), colors.white),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#EEF3FA')]),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 1), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 1), (-1, -1), 5),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#AAAAAA')),
        ('LINEBELOW', (0, 0), (-1, 0), 1.5, colors.HexColor('#1E3F66')),
    ]

    note_style = ParagraphStyle('Note', parent=styles['Normal'], fontSize=7, textColor=colors.HexColor('#555555'))
    story = [Paragraph(escape(title), title_style), Spacer(1, 0.3 * cm)]
    for position, chunk in enumerate(chunks):
        if position:
            story.append(PageBreak())
        if len(chunks) > 1:
            story.append(Paragraph(f"Sessions {chunk.start + 1} to {chunk.stop} of {num_sessions}", note_style))
            story.append(Spacer(1, 0.2 * cm))
        story.append(build_table(chunk))
    if notes:
        story.append(Spacer(1, 0.3 * cm))
        story += [Paragraph(escape(note), note_style) for note in notes]
    doc.build(story)
    buffer.seek(0)
    return buffer


