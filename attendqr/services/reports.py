def session_header_lines(class_session):
    if class_session.special_title:
        return [class_session.special_title]
    subject = class_session.subject
    if not subject:
        return ['Special Class']
    paper_code = normalize_paper_code(subject.paper_code)
    return [subject.name, paper_code] if paper_code else [subject.name]


def _excel_safe(value):
    """Stop spreadsheet apps from treating user-entered text as a formula."""
    if isinstance(value, str) and value[:1] in ('=', '+', '-', '@', '\t', '\r'):
        return "'" + value
    return value


def export_filename(department, semester, sessions, filters):
    if filters.subject_id and sessions and sessions[0].subject:
        subject = sessions[0].subject
        base = normalize_paper_code(subject.paper_code) or subject.name
        name = f'{base}_attendance'
    else:
        base = department.branch_name or department.course_name
        name = f'{base}_{semester.name}_attendance'
    return ''.join(ch if ch.isalnum() or ch in '-_.' else '_' for ch in name)


def build_export_rows(sessions, rows):
    headers = ['Roll No', 'Name', 'Email'] + [session_header_lines(s) for s in sessions] + ['Total', '%']
    data = []
    for row in rows:
        student = row['student']
        line = [student.roll_no, student.name, student.email]
        line += ['P' if row['attendance'][s.id] else 'A' for s in sessions]
        line.append(row['total'])
        line.append(f"{round(row['total'] / len(sessions) * 100, 1)}%" if sessions else "0%")
        data.append(line)
    return headers, data


def render_excel(headers, data):
    workbook = openpyxl.Workbook()
    sheet = workbook.active
    sheet.title = "Attendance Report"
    header_font = openpyxl.styles.Font(color="FFFFFF", bold=True)
    header_fill = openpyxl.styles.PatternFill(start_color="366092", end_color="366092", fill_type="solid")

    for col_idx, header in enumerate(headers, 1):
        text = ' - '.join(header) if isinstance(header, list) else header
        cell = sheet.cell(row=1, column=col_idx, value=_excel_safe(text))
        cell.font = header_font
        cell.fill = header_fill
    for row_idx, row in enumerate(data, 2):
        for col_idx, value in enumerate(row, 1):
            sheet.cell(row=row_idx, column=col_idx, value=_excel_safe(value))

    buffer = io.BytesIO()
    workbook.save(buffer)
    buffer.seek(0)
    return buffer


def render_pdf(headers, data, title):
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_CENTER, TA_LEFT
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import cm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table

    buffer = io.BytesIO()
    margin = 1.5 * cm
    usable_width = A4[0] - 2 * margin
    doc = SimpleDocTemplate(buffer, pagesize=A4, leftMargin=margin, rightMargin=margin,
                            topMargin=margin, bottomMargin=margin)

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle('ReportTitle', parent=styles['Heading1'], fontSize=14,
                                 textColor=colors.HexColor('#366092'), spaceAfter=8, alignment=TA_LEFT)
    header_style = ParagraphStyle('HeaderCell', fontSize=7, textColor=colors.whitesmoke,
                                  alignment=TA_CENTER, leading=9)
    body_style = ParagraphStyle('BodyCell', fontSize=8, alignment=TA_CENTER, leading=10)

    def cell(value, style):
        # Paragraph parses markup, so every user-supplied value is escaped; only our own
        # line breaks between header parts are real markup.
        lines = value if isinstance(value, list) else [value]
        return Paragraph('<br/>'.join(escape('' if v is None else str(v)) for v in lines), style)

    table_data = [[cell(h, header_style) for h in headers]]
    table_data += [[cell(v, body_style) for v in row] for row in data]

    # Fixed widths for Roll No, Name, Email, Total, %; sessions share the rest.
    col_roll, col_name, col_email, col_total, col_pct = 2.0 * cm, 3.2 * cm, 4.2 * cm, 1.1 * cm, 1.6 * cm
    fixed_width = col_roll + col_name + col_email + col_total + col_pct
    num_sessions = max(len(headers) - 5, 0)
    session_width = min(max((usable_width - fixed_width) / num_sessions, 1.5 * cm), 3.5 * cm) if num_sessions else 0
    col_widths = [col_roll, col_name, col_email] + [session_width] * num_sessions + [col_total, col_pct]
    total_width = sum(col_widths)
    if 0 < total_width < usable_width:
        col_widths = [w * usable_width / total_width for w in col_widths]

    table = Table(table_data, colWidths=col_widths, repeatRows=1)
    table.setStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#366092')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, 0), 7),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 8),
        ('TOPPADDING', (0, 0), (-1, 0), 8),
        ('BACKGROUND', (0, 1), (-1, -1), colors.white),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#EEF3FA')]),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 1), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 1), (-1, -1), 5),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#AAAAAA')),
        ('LINEBELOW', (0, 0), (-1, 0), 1.5, colors.HexColor('#1E3F66')),
    ])

    doc.build([Paragraph(escape(title), title_style), Spacer(1, 0.3 * cm), table])
    buffer.seek(0)
    return buffer
